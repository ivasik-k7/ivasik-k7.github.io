/* ------------------------------------------------------- the picnic table -- */

/**
 * The A-frame picnic table, 58×30, seen from the walk: far bench as a thin
 * lit strip beyond the top, the tabletop as a real plank face, the near bench
 * low and wide in front, X-legs at the ends. Three depths in one object,
 * which is the whole reason to look at it.
 */
export function picnicMap(): SpriteMap {
  const W = 58;
  const H = 30;
  const g = grid(W, H);

  /* far bench: a strip at the very top, mostly hidden by the tabletop */
  fill(g, 6, 0, 46, 2, "m");
  fill(g, 6, 0, 46, 1, "b");

  /* tabletop: top face, three planks with gaps, then the front edge */
  fill(g, 2, 3, 54, 6, "b");
  fill(g, 2, 3, 54, 1, "h");
  for (const gap of [5, 7]) fill(g, 3, gap, 52, 1, "m");
  fill(g, 2, 9, 54, 2, "l");
  fill(g, 2, 11, 54, 1, "d");

  /* the X legs at both ends, stepped diagonals */
  for (let i = 0; i < 12; i++) {
    put(g, 6 + i, 12 + i, "l");
    put(g, 7 + i, 12 + i, "l");
    put(g, 17 - i, 12 + i, "m");
    put(g, 18 - i, 12 + i, "m");
    put(g, 40 + i, 12 + i, "l");
    put(g, 41 + i, 12 + i, "l");
    put(g, 51 - i, 12 + i, "m");
    put(g, 52 - i, 12 + i, "m");
  }

  /* near bench: seat face + front edge, low across the whole front */
  fill(g, 0, 21, 58, 3, "b");
  fill(g, 0, 21, 58, 1, "h");
  fill(g, 0, 24, 58, 2, "l");
  /* its legs */
  fill(g, 4, 26, 3, 4, "d");
  fill(g, 51, 26, 3, 4, "d");

  /* somebody's bottle on the tabletop */
  fill(g, 34, 0, 2, 4, "g");
  put(g, 34, 0, "G");
  return toMap(g);
}

