import type { ActorDef, AnyWorld, SpriteMap, SpritePalette } from "@/engine";

/**
 * bandProps — furniture that stands INSIDE the walkable band, as one-frame
 * runtime actors.
 *
 * WHY ACTORS. Scene artwork is one SVG behind every figure; the Foreground
 * plane is in front of every figure, always. Neither can express "the player
 * walked behind the barrel". The runtime already solves this for people: in a
 * ground-band scene every actor is depth-sorted by its feet line
 * (z = 20 + y), against the player and against each other. So a barrel table
 * becomes an actor with one frame and no brain — it stands there, and the
 * sorting the engine already does for characters makes it a physical object
 * for free. The pattern costs one <div> per prop; a scene carries half a
 * dozen, not fifty — everything glued to the back line (y = 150) stays in the
 * cheap SVG planes, because the player's feet can never be behind the back
 * line and flat art there sorts correctly by construction.
 *
 * THE ART. Frames are sprite maps at cell 1, generated by small functions
 * rather than typed by hand — a cylinder's rim is math, not forty rows of
 * string literal. Conventions match the rest of the kit: light from the
 * top-left; a visible TOP FACE, because the camera sits slightly above eye
 * height (the band itself is the proof: you can see the ground plane); a
 * one-pixel lit edge on top/left surfaces and a shaded column on the right;
 * `.` is transparent.
 *
 * Every prop here expects the scene to provide, at the same coordinates:
 *   - a GroundBlocker matching its footprint, and
 *   - a cast shadow painted in the scene's ground/static plane (the shadow
 *     must render UNDER every figure, so it cannot live on the actor).
 */

/* ------------------------------------------------------------ the helper -- */

/** A standing object with one frame: the whole ActorDef, minus the brain. */
export function propActor<W extends AnyWorld>(
  id: string,
  x: number,
  y: number,
  map: SpriteMap,
  palette: SpritePalette,
  opts?: { visible?: (world: W) => boolean; facing?: 1 | -1 },
): ActorDef<W> {
  return {
    id,
    width: map[0]?.length ?? 0,
    height: map.length,
    cell: 1,
    frames: { s: map },
    palette,
    idleFrame: "s",
    x,
    y,
    facing: opts?.facing ?? 1,
    visible: opts?.visible,
  };
}

/* --------------------------------------------------------------- drawing -- */

type Grid = string[][];

function grid(w: number, h: number): Grid {
  return Array.from({ length: h }, () => Array.from({ length: w }, () => "."));
}

function toMap(g: Grid): SpriteMap {
  return g.map((row) => row.join(""));
}

function put(g: Grid, x: number, y: number, ch: string) {
  if (y >= 0 && y < g.length && x >= 0 && x < (g[0]?.length ?? 0)) g[y][x] = ch;
}

function fill(g: Grid, x: number, y: number, w: number, h: number, ch: string) {
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) put(g, x + i, y + j, ch);
}

/** Half-width of an ellipse of horizontal radius rx at row offset t∈[-1,1]. */
function hw(rx: number, t: number): number {
  const s = 1 - t * t;
  return s <= 0 ? 0 : Math.max(1, Math.round(rx * Math.sqrt(s)));
}

/* ------------------------------------------------------------ the barrel -- */

/**
 * A beer keg stood on end as a table: 22×44 (0.58 m wide, 1.15 m to the rim).
 * The top face is what sells the volume — an ellipse of lit steel with the
 * far rim bright and the near rim in shade — and the chime hoops wrap it,
 * bending down at the edges the way a hoop on a cylinder must.
 */
export function barrelMap(withGlasses: boolean): SpriteMap {
  const W = 22;
  const H = 44;
  const RX = 10;
  const RY = 4;
  const cx = 11;
  const g = grid(W, H);
  const topCy = RY; // ellipse centre row of the top face

  /* body: columns shaded as a cylinder — highlight band left of centre */
  for (let y = topCy; y < H; y++) {
    for (let x = cx - RX; x <= cx + RX - 1; x++) {
      const t = (x - (cx - RX)) / (2 * RX - 1); // 0..1 across the drum
      let ch = "b";
      if (t < 0.08) ch = "d";
      else if (t < 0.2) ch = "m";
      else if (t < 0.42)
        ch = "h"; // the highlight band
      else if (t < 0.72) ch = "b";
      else if (t < 0.9) ch = "m";
      else ch = "d";
      put(g, x, y, ch);
    }
  }
  /* round the drum's foot corners off */
  for (const y of [H - 1]) {
    put(g, cx - RX, y, ".");
    put(g, cx + RX - 1, y, ".");
  }

  /* hoops: two pixel bands that dip at the edges (they wrap the curve) */
  for (const hoopY of [14, 26, 38]) {
    for (let x = cx - RX; x <= cx + RX - 1; x++) {
      const t = Math.abs((x - cx + 0.5) / RX);
      const dip = t > 0.86 ? 1 : 0;
      put(g, x, hoopY + dip, "k");
      put(g, x, hoopY + dip + 1, "K");
    }
  }

  /* the top face, painted last so the rim owns its pixels */
  for (let dy = -RY; dy <= RY; dy++) {
    const w2 = hw(RX, dy / RY);
    for (let x = cx - w2; x <= cx + w2 - 1; x++) {
      const rim = x === cx - w2 || x === cx + w2 - 1 || dy === -RY || dy === RY;
      put(g, x, topCy + dy, rim ? (dy < 0 ? "h" : "K") : "t");
    }
  }
  /* the puddle of last night's beer on the top face */
  put(g, cx + 2, topCy, "T");
  put(g, cx + 3, topCy, "T");

  if (withGlasses) {
    /* two plastic cups standing on the far half of the top face */
    fill(g, cx - 5, topCy - 6, 3, 6, "c");
    put(g, cx - 5, topCy - 6, "C");
    fill(g, cx + 4, topCy - 5, 3, 5, "c");
    put(g, cx + 4, topCy - 5, "C");
  }
  return toMap(g);
}

