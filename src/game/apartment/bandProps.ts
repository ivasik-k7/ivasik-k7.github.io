/* ---------------------------------------------------------- the drum table -- */

/**
 * A cable drum on its end, 32×26 — the street's found furniture. The top is
 * one big plank disc, which is the most top-face any object here has.
 */
export function drumMap(): SpriteMap {
  const W = 32;
  const H = 26;
  const RX = 15;
  const RY = 5;
  const cx = 16;
  const g = grid(W, H);
  /* the side: slats under the disc */
  for (let y = RY; y < H; y++) {
    for (let x = cx - RX + 1; x <= cx + RX - 2; x++) {
      const t = (x - (cx - RX)) / (2 * RX - 1);
      put(g, x, y, t < 0.2 ? "m" : t < 0.5 ? "b" : t < 0.8 ? "m" : "l");
    }
  }
  for (const sx of [6, 12, 19, 25]) {
    for (let y = RY + 1; y < H - 1; y++) put(g, sx, y, "d");
  }
  /* the disc */
  for (let dy = -RY; dy <= RY; dy++) {
    const w2 = hw(RX, dy / RY);
    for (let x = cx - w2; x <= cx + w2 - 1; x++) {
      const rim = x === cx - w2 || x === cx + w2 - 1 || dy === -RY || dy === RY;
      put(g, x, RY + dy, rim ? (dy < 0 ? "h" : "d") : "t");
    }
  }
  /* plank joints across the disc, and the axle hole */
  for (let x = cx - 12; x <= cx + 11; x++) {
    put(g, x, RY - 2, "T");
    put(g, x, RY + 2, "T");
  }
  fill(g, cx - 2, RY - 1, 4, 2, "d");
  /* wax drips from last week's candle */
  put(g, cx + 8, RY - 1, "w");
  put(g, cx + 8, RY, "w");
  return toMap(g);
}

