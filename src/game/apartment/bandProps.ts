/* ------------------------------------------------------- the PKP trolley -- */

/**
 * The platform barrow, 40×34 — PKP property since before anyone asked. A flat
 * bed on two spoked wheels with an upright handle, parked mid-platform at the
 * angle of something abandoned rather than placed. The bed's top face carries
 * one strapped bundle, because an empty trolley is a prop and a loaded one is
 * a job someone walked away from.
 */
export function trolleyMap(): SpriteMap {
  const W = 40;
  const H = 34;
  const g = grid(W, H);
  /* the handle, upright at the left end */
  fill(g, 3, 0, 2, 18, "m");
  fill(g, 1, 0, 6, 2, "h");
  /* the bed: top face, then the frame edge */
  fill(g, 2, 16, 36, 3, "h");
  fill(g, 2, 19, 36, 3, "b");
  fill(g, 2, 22, 36, 2, "d");
  /* the bundle on the bed, strapped twice */
  fill(g, 12, 8, 16, 8, "s");
  fill(g, 12, 8, 16, 1, "S");
  fill(g, 15, 8, 2, 8, "k");
  fill(g, 23, 8, 2, 8, "k");
  /* two spoked wheels */
  for (const cx of [10, 30]) {
    for (let dy = -5; dy <= 5; dy++) {
      const w2 = hw(5, dy / 5);
      for (let x = cx - w2; x <= cx + w2 - 1; x++) {
        const rim = x === cx - w2 || x === cx + w2 - 1 || Math.abs(dy) === 5;
        put(g, x, 28 + dy, rim ? "d" : "m");
      }
    }
    put(g, cx - 1, 27, "k");
    put(g, cx, 28, "k");
    put(g, cx - 4, 28, "k");
    put(g, cx + 3, 28, "k");
  }
  return toMap(g);
}

